/**
 * Returns all Indian States & Union Territories sorted alphabetically.
 */
export function getIndianStates() {
  return Object.keys(INDIA_STATES_AND_CITIES).sort((a, b) => a.localeCompare(b));
}

/**
 * Returns all cities for a given Indian State sorted alphabetically.
 */
export function getCitiesForState(stateName) {
  if (!stateName || !INDIA_STATES_AND_CITIES[stateName]) {
    return [];
  }
  return [...INDIA_STATES_AND_CITIES[stateName]].sort((a, b) => a.localeCompare(b));
}

/**
 * Parses an existing location string (e.g., "Bengaluru, Karnataka" or "madiwala, Bengaluru, Karnataka" or "Kerala")
 * back into matching state and city.
 */
export function parseLocation(locationString) {
  if (!locationString || typeof locationString !== 'string') {
    return { state: '', city: '' };
  }

  const clean = locationString.trim();
  const states = getIndianStates();

  // 1. Check if the string matches "City, State" directly
  const parts = clean.split(',').map((p) => p.trim());
  if (parts.length >= 2) {
    const candidateCity = parts[parts.length - 2];
    const candidateState = parts[parts.length - 1];

    const matchedState = states.find(
      (s) => s.toLowerCase() === candidateState.toLowerCase()
    );
    if (matchedState) {
      const cities = getCitiesForState(matchedState);
      const matchedCity = cities.find(
        (c) => c.toLowerCase() === candidateCity.toLowerCase()
      );
      if (matchedCity) {
        return { state: matchedState, city: matchedCity };
      }
      return { state: matchedState, city: candidateCity };
    }
  }

  // 2. Check if string contains any known State name
  for (const s of states) {
    if (clean.toLowerCase().includes(s.toLowerCase())) {
      const cities = getCitiesForState(s);
      for (const c of cities) {
        if (clean.toLowerCase().includes(c.toLowerCase())) {
          return { state: s, city: c };
        }
      }
      return { state: s, city: cities[0] || '' };
    }
  }

  // 3. Check if string contains any known City name
  for (const s of states) {
    const cities = getCitiesForState(s);
    for (const c of cities) {
      if (clean.toLowerCase().includes(c.toLowerCase())) {
        return { state: s, city: c };
      }
    }
  }

  // 4. Fallback defaults if no match found
  return { state: '', city: '' };
}
