  static List<String> getIndianStates() {
    return statesAndCities.keys.toList()..sort();
  }

  static List<String> getCitiesForState(String? state) {
    if (state == null || state.isEmpty) return [];
    return statesAndCities[state] ?? [];
  }

  static ({String state, String city}) parseLocation(String rawLocation) {
    if (rawLocation.trim().isEmpty) return (state: '', city: '');

    final clean = rawLocation.trim();
    final parts = clean.split(',').map((p) => p.trim()).toList();

    final states = getIndianStates();

    if (parts.length >= 2) {
      final candidateCity = parts[0];
      final candidateState = parts[1];

      final matchedState = states.firstWhere(
        (s) => s.toLowerCase() == candidateState.toLowerCase(),
        orElse: () => '',
      );

      if (matchedState.isNotEmpty) {
        final cities = getCitiesForState(matchedState);
        final matchedCity = cities.firstWhere(
          (c) => c.toLowerCase() == candidateCity.toLowerCase(),
          orElse: () => candidateCity,
        );
        return (state: matchedState, city: matchedCity);
      }
    }

    for (final s in states) {
      if (clean.toLowerCase().contains(s.toLowerCase())) {
        final cities = getCitiesForState(s);
        for (final c in cities) {
          if (clean.toLowerCase().contains(c.toLowerCase())) {
            return (state: s, city: c);
          }
        }
        return (state: s, city: cities.isNotEmpty ? cities.first : '');
      }
    }

    for (final s in states) {
      final cities = getCitiesForState(s);
      for (final c in cities) {
        if (clean.toLowerCase().contains(c.toLowerCase())) {
          return (state: s, city: c);
        }
      }
    }

    return (state: '', city: '');
  }
